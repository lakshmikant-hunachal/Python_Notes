#advantages of Python:
# 1. Easy to Learn and Use: Python's simple syntax makes it accessible for beginners.
# 2. Versatile: Python can be used for a wide range of applications, from web development to data science.
# 3. Large Community: Python has a large and active community that contributes to its development and provides support through forums and tutorials.                    
# 4. Extensive Libraries: Python has a vast collection of libraries and frameworks that simplify development tasks.


#disadvantages of Python:
# 1. Slower Execution Speed: Python is an interpreted language, which can make it slower than compiled languages like C or C++.
# 2. Not Ideal for Mobile Development: Python is not commonly used for mobile app development   
# 3. Global Interpreter Lock (GIL): Python's GIL can be a limitation for multi-threaded applications, as it prevents multiple native threads from executing Python bytecodes at once.   
#4. Memory Consumption: Python's memory consumption can be higher compared to other languages, which may be a concern for memory-intensive applications.